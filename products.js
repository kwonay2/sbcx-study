export function calcResults(task) {
  const first = FIRST[task.set];
  if (task.x1 === '결정') {
    return first.map((p, i) =>
      task.exclP[i] || task.exclB[i] ? { ...REPL[task.set][i], isNew: true } : { ...p, isNew: false }
    );
  }
  const changed = { fit: task.conds.fit !== DEF.fit, mat: task.conds.mat !== DEF.mat, len: task.conds.len !== DEF.len };
  return POOL[task.set]
    .map((p, k) => ({
      p,
      k,
      score: ['fit', 'mat', 'len'].reduce((a, d) => a + (p[d] === task.conds[d] ? (changed[d] ? 2 : 1) : 0), 0)
    }))
    .sort((a, b) => b.score - a.score || a.k - b.k)
    .slice(0, 3)
    .map((x) => ({ ...x.p, isNew: true }));
}

function bottomOf(len) {
  return len === '크롭' ? 40 : len === '롱' ? 60 : 52;
}
// 상품 사진 자리표시: 기장에 따라 길이가 바뀌는 니트 실루엣
export function sweaterPath(len) {
  const b = bottomOf(len);
  return `M24 6 Q32 12 40 6 L50 9 Q56 12 58 44 L51 46 L46 22 L46 ${b} L18 ${b} L18 22 L13 46 L6 44 Q8 12 14 9 Z`;
}
export function hemPath(len) {
  const b = bottomOf(len) - 4;
  return `M18 ${b} L46 ${b}`;
}

export function won(n) {
  return n.toLocaleString('ko-KR') + '원';
}
